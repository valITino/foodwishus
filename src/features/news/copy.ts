// Every word of the bell and the list behind it. English and German keep the same
// shape. German is informal ("du"). Lines with a name are used when the change itself
// says who did it; the plain ones when either of the two could have.

const en = {
  title: 'Kitchen news',
  bell: (unseen: number) => (unseen === 0 ? 'Kitchen news' : unseen === 1 ? 'Kitchen news, 1 new' : `Kitchen news, ${unseen} new`),
  fresh: 'New',
  emptyTitle: 'Nothing new',
  emptyBody: 'When the other one proposes, plans, serves or answers, it shows up here.',
  /** "Today, 18:40" */
  at: (day: string, time: string) => `${day}, ${time}`,
  lines: {
    proposedForCook: (who: string, dish: string) => `${who} wishes for ${dish}.`,
    proposed: (who: string, dish: string) => `${who} put ${dish} on the wishlist.`,
    proposedPlain: (dish: string) => `${dish} is new on the wishlist.`,
    plannedBy: (who: string, dish: string, when: string) => `${who} planned ${dish} for ${when}.`,
    planned: (dish: string, when: string) => `${dish} is planned for ${when}.`,
    plannedSomeDay: (dish: string) => `${dish} is planned.`,
    moved: (dish: string, when: string) => `${dish} moved to ${when}.`,
    unplanned: (dish: string) => `${dish} is off the calendar and back on the wishlist.`,
    servedForEater: (who: string, dish: string) => `${who} served ${dish}. Proof, please.`,
    served: (dish: string) => `${dish} is on the table.`,
    eaten: (who: string, dish: string) => `${who} ate ${dish} and handed in the verdict.`,
    eatenPlain: (dish: string) => `${dish} was eaten. The verdict is in.`,
    answered: (who: string, dish: string) => `${who} answered your verdict on ${dish}.`,
    reacted: (who: string, dish: string) => `${who} reacted to your verdict on ${dish}.`,
    answeredPlain: (dish: string) => `The verdict on ${dish} got an answer.`,
    skipped: (dish: string) => `${dish} was skipped.`,
    skippedBecause: (dish: string, reason: string) => `${dish} was skipped (${reason}).`,
    removed: (dish: string) => `${dish} was taken off the list.`,
    hearts: (who: string, dish: string, hearts: number) => `${who} gave ${dish} ${hearts} of 5 hearts.`,
    heartsPlain: (dish: string, hearts: number) => `${dish} got ${hearts} of 5 hearts.`,
    note: (who: string, dish: string) => `${who} left a note on ${dish}.`,
    notePlain: (dish: string) => `${dish} has a new note.`,
    cookYou: (dish: string) => `You cook ${dish} now.`,
    cook: (who: string, dish: string) => `${who} cooks ${dish} now.`,
    cookPlain: (dish: string) => `Somebody else cooks ${dish} now.`,
    dish: (who: string, dish: string) => `${who} added ${dish} to the recipe book.`,
    dishPlain: (dish: string) => `${dish} is new in the recipe book.`,
    dishes: (count: number) => `${count} new dishes in the recipe book.`,
    menu: (who: string, menu: string) => `${who} put together a menu: ${menu}.`,
    menuPlain: (menu: string) => `A new menu: ${menu}.`,
    joined: (who: string) => `${who} joined the kitchen.`,
    basketOne: (who: string, what: string) => `${who} put ${what} on the basket.`,
    basketOnePlain: (what: string) => `New on the basket: ${what}.`,
    basketMany: (who: string, count: number) => `${who} put ${count} things on the basket.`,
    basketManyPlain: (count: number) => `${count} new things on the basket.`,
    forkOne: (what: string) => `Fork thinks ${what} is running low.`,
    forkMany: (count: number) => `Fork thinks ${count} things are running low.`,
  },
}

export type NewsCopy = typeof en

